const context = createContext(window.APP_DATA);
initIndicators(context);
initInterest(context);
const repaymentView = initRepayment(context);
const fiscalTimeline = createFiscalTimeline(context.data);
const financesView = initFinances(context, fiscalTimeline);
const debtView = initDebtChart(context, fiscalTimeline);
initSpending(context);
const budgetView = initBudget(context);
const growthView = initGrowthChart(context);
const resizeCharts = () => { repaymentView.resize(); debtView.resize(); budgetView.resize(); financesView.resize(); growthView.resize(); };
context.charts.subscribe(() => { repaymentView.refresh(); debtView.refresh(); budgetView.refresh(); financesView.refresh(); growthView.refresh(); });
new ResizeObserver(resizeCharts).observe(document.querySelector('main'));
window.addEventListener('resize', resizeCharts);
context.reducedMotion.addEventListener('change', () => { repaymentView.refresh(); debtView.refresh(); budgetView.refresh(); financesView.refresh(); growthView.refresh(); });
